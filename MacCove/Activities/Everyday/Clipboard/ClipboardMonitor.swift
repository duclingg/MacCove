import AppKit
import UniformTypeIdentifiers

/// Copies, as the island shows them: a quick "Copied", what it was and
/// where from, and the last few to copy again.
///
/// Nothing tells other apps the pasteboard changed, so its change count is
/// checked twice a second. History is kept in memory for 24 hours, never
/// on disk, and only while Clipboard History is turned on. Concealed copies
/// (passwords, marked so by password managers as nspasteboard.org asks)
/// show as hidden and are never kept; transient and auto-generated ones,
/// which apps put there for themselves, aren't shown at all.
@Observable
final class ClipboardMonitor {
    enum Event {
        case copied
        /// Dismissed, cleared, or turned off.
        case ended
    }

    enum Kind: Equatable {
        case text
        case link
        /// A hex colour, like #3E9BFF.
        case color
        case image
        case file
    }

    struct Item: Identifiable, Equatable {
        let id = UUID()
        let kind: Kind
        /// What it shows: the text, the link, the file's name.
        let preview: String
        /// The app in front when it was copied.
        let sourceName: String?
        var copiedAt: Date
        /// What was on the pasteboard, a dictionary per pasteboard item, to
        /// put back.
        fileprivate let contents: [[NSPasteboard.PasteboardType: Data]]

        static func == (lhs: Item, rhs: Item) -> Bool {
            lhs.id == rhs.id && lhs.copiedAt == rhs.copiedAt
        }
    }

    enum Shown: Equatable {
        case copied(Item)
        /// A password: only that one was copied, and where from.
        case concealed(sourceName: String?)
        case history
    }

    static let enabledKey = "ClipboardHistoryEnabled"

    /// What the island is showing, `nil` when it isn't.
    private(set) var shown: Shown?
    /// Newest first.
    private(set) var history: [Item] = []
    /// Copies aren't shown or kept until then.
    private(set) var pausedUntil: Date?

    @ObservationIgnored var onEvent: ((Event) -> Void)?
    /// Whether the island is open or under the cursor, when a copy waits to
    /// leave until you're done with it.
    @ObservationIgnored var isInUse: () -> Bool = { false }

    @ObservationIgnored private var changeCount = 0
    @ObservationIgnored private var polling: Task<Void, Never>?
    @ObservationIgnored private var dismissal: Task<Void, Never>?
    /// The copy has had its moment, and leaves once the island isn't in use.
    @ObservationIgnored private var isDue = false

    static let historyLimit = 4
    private static let historyLifetime: TimeInterval = 24 * 60 * 60
    private static let pollInterval: Duration = .milliseconds(500)
    /// How long "Copied" stays in the pill.
    private static let copiedDuration: Duration = .seconds(2.5)
    private static let pauseDuration: TimeInterval = 60 * 60
    /// Larger pasteboard data, a huge TIFF say, isn't kept.
    private static let maxDataSize = 20 * 1024 * 1024

    /// See nspasteboard.org.
    private static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("com.agilebits.onepassword"),
    ]
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    /// What's put back when a copy is copied again.
    private static let keptTypes: [NSPasteboard.PasteboardType] = [.fileURL, .URL, .string, .rtf, .html, .png, .tiff]

    static var isEnabled: Bool {
        UserDefaults.standard.bool(forKey: enabledKey)
    }

    /// The clipboard is private. Until macOS has asked about MacCove, it
    /// reads freely; once it has, it asks on every copy, or refuses, unless
    /// set to Always Allow in Privacy & Security › Paste from Other Apps.
    static var isAccessRestricted: Bool {
        [.ask, .alwaysDeny].contains(NSPasteboard.general.accessBehavior)
    }

    static func openAccessSettings() {
        // The pane's current identifier; the old com.apple.preference.security
        // one no longer opens anything.
        SystemSettings.openPrivacy("Privacy_Pasteboard")
    }

    /// Starts watching from what's on the pasteboard now, which was copied
    /// before and isn't shown.
    func start() {
        guard polling == nil else { return }
        changeCount = NSPasteboard.general.changeCount
        polling = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: Self.pollInterval)
                guard let self else { return }
                self.check()
            }
        }
    }

    /// Turned off: what was kept goes too.
    func stop() {
        polling?.cancel()
        polling = nil
        history = []
        pausedUntil = nil
        dismiss()
    }

    func showHistory() {
        pruneHistory()
        dismissal?.cancel()
        isDue = true
        shown = .history
    }

    /// Puts a copy from the history back on the pasteboard, as the newest.
    func copy(_ item: Item) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.writeObjects(item.contents.map { contents in
            let pasteboardItem = NSPasteboardItem()
            for (type, data) in contents {
                pasteboardItem.setData(data, forType: type)
            }
            return pasteboardItem
        })
        // Our own change, so it isn't announced as a new copy.
        changeCount = pasteboard.changeCount
        var copied = item
        copied.copiedAt = .now
        history.removeAll { $0.id == item.id }
        history.insert(copied, at: 0)
    }

    /// Takes back the copy being shown: off the pasteboard, if nothing has
    /// been copied since, and out of the history.
    func clear() {
        if case let .copied(item)? = shown {
            history.removeAll { $0.id == item.id }
        }
        let pasteboard = NSPasteboard.general
        if pasteboard.changeCount == changeCount {
            pasteboard.clearContents()
            changeCount = pasteboard.changeCount
        }
        dismiss()
    }

    func clearHistory() {
        history = []
        dismiss()
    }

    func pause() {
        pausedUntil = .now.addingTimeInterval(Self.pauseDuration)
    }

    func resume() {
        pausedUntil = nil
    }

    func dismiss() {
        dismissal?.cancel()
        isDue = false
        guard shown != nil else { return }
        shown = nil
        onEvent?(.ended)
    }

    /// Takes away a copy whose time is up, after `delay`, unless the island
    /// is open or under the cursor; then it waits to be asked again.
    func leaveIfDue(after delay: Duration = .zero) {
        guard isDue, shown != nil else { return }
        dismissal?.cancel()
        dismissal = Task { [weak self] in
            try? await Task.sleep(for: delay)
            guard !Task.isCancelled, let self, self.isDue, !self.isInUse() else { return }
            self.dismiss()
        }
    }

    // MARK: - Watching the pasteboard

    private func check() {
        pruneHistory()
        if let pausedUntil, pausedUntil <= .now {
            self.pausedUntil = nil
        }

        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        // Refused, nothing would come back. Asking, reading prompts you,
        // which is how MacCove first appears in Settings to be allowed.
        guard pausedUntil == nil, pasteboard.accessBehavior != .alwaysDeny else { return }

        let types = Set(pasteboard.types ?? [])
        // Empty when something cleared it.
        guard !types.isEmpty, types.isDisjoint(with: Self.ignoredTypes) else { return }
        let sourceName = NSWorkspace.shared.frontmostApplication?.localizedName
        guard types.isDisjoint(with: Self.concealedTypes) else {
            show(.concealed(sourceName: sourceName))
            return
        }
        guard let item = Self.item(from: pasteboard, sourceName: sourceName) else { return }
        // The same thing copied again moves up rather than repeating.
        history.removeAll { $0.contents == item.contents }
        history.insert(item, at: 0)
        if history.count > Self.historyLimit {
            history.removeLast(history.count - Self.historyLimit)
        }
        show(.copied(item))
    }

    /// A new copy replaces whatever was showing, the history too.
    private func show(_ newShown: Shown) {
        shown = newShown
        isDue = false
        onEvent?(.copied)
        dismissal?.cancel()
        dismissal = Task { [weak self] in
            try? await Task.sleep(for: Self.copiedDuration)
            guard !Task.isCancelled, let self else { return }
            self.isDue = true
            self.leaveIfDue()
        }
    }

    /// Only touches the history when something has expired, so watching
    /// doesn't redraw the island twice a second.
    private func pruneHistory() {
        let cutoff = Date.now.addingTimeInterval(-Self.historyLifetime)
        guard let oldest = history.last, oldest.copiedAt < cutoff else { return }
        history.removeAll { $0.copiedAt < cutoff }
    }

    // MARK: - Reading a copy

    private static func item(from pasteboard: NSPasteboard, sourceName: String?) -> Item? {
        let contents = (pasteboard.pasteboardItems ?? []).map { pasteboardItem in
            var data: [NSPasteboard.PasteboardType: Data] = [:]
            for type in keptTypes where pasteboardItem.types.contains(type) {
                if let value = pasteboardItem.data(forType: type), value.count <= maxDataSize {
                    data[type] = value
                }
            }
            return data
        }
        .filter { !$0.isEmpty }
        guard !contents.isEmpty, let (kind, preview) = describe(pasteboard) else { return nil }
        return Item(kind: kind, preview: preview, sourceName: sourceName, copiedAt: .now, contents: contents)
    }

    /// Files by name, then text, then a picture by its size.
    private static func describe(_ pasteboard: NSPasteboard) -> (Kind, String)? {
        let files = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        if let first = files.first {
            let isImage = files.allSatisfy { (try? $0.resourceValues(forKeys: [.contentTypeKey]).contentType?.conforms(to: .image)) == true }
            let name = first.deletingPathExtension().lastPathComponent
            return (isImage ? .image : .file, files.count == 1 ? name : "\(name) and \(files.count - 1) more")
        }
        if let string = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !string.isEmpty {
            return (kind(of: string), String(string.prefix(2000)))
        }
        if let image = NSImage(pasteboard: pasteboard) {
            return (.image, "Image, \(Int(image.size.width)) × \(Int(image.size.height))")
        }
        return nil
    }

    private static func kind(of string: String) -> Kind {
        let hex = string.dropFirst()
        if string.hasPrefix("#"), hex.count == 3 || hex.count == 6, hex.allSatisfy(\.isHexDigit) {
            return .color
        }
        if !string.contains(where: \.isWhitespace), let url = URL(string: string),
           let scheme = url.scheme?.lowercased(), ["http", "https", "mailto", "ftp"].contains(scheme) {
            return .link
        }
        return .text
    }
}

#if DEBUG
extension ClipboardMonitor {
    /// What's shown and kept stays as given, for SwiftUI previews.
    static func preview(_ shown: Shown?, history: [Item] = [], pausedUntil: Date? = nil) -> ClipboardMonitor {
        let monitor = ClipboardMonitor()
        monitor.shown = shown
        monitor.history = history
        monitor.pausedUntil = pausedUntil
        return monitor
    }

    static func previewItem(_ kind: Kind, _ preview: String, from sourceName: String? = nil, minutesAgo: Double = 0) -> Item {
        Item(kind: kind, preview: preview, sourceName: sourceName, copiedAt: .now.addingTimeInterval(-minutesAgo * 60), contents: [])
    }
}
#endif
